"""Tests for the jira-release-tool CLI."""
from __future__ import annotations

import json
from pathlib import Path

import pytest

from orchestrator.entry.cli import (
    CliDeps,
    build_parser,
    build_ticket_payload,
    main,
    validate_config,
)


def _good_config(tmp_path: Path) -> Path:
    p = tmp_path / "r.yml"
    p.write_text(
        """\
workspace: default
releases:
  - 2026.4.04.20
summary: Production Deployment — v1
priority: Medium
approvers:
  - alice
approver_groups:
  - Command Center
""",
        encoding="utf-8",
    )
    return p


class TestValidateConfig:
    def test_required_keys_missing(self):
        v = validate_config({})
        assert not v.ok
        assert any("workspace" in e for e in v.errors)
        assert any("releases" in e for e in v.errors)

    def test_happy_path(self):
        v = validate_config({"workspace": "x", "releases": ["v1"]})
        assert v.ok

    def test_unknown_key_is_warning_not_error(self):
        v = validate_config({"workspace": "x", "releases": ["v1"], "bogus": 1})
        assert v.ok
        assert any("bogus" in w for w in v.warnings)

    def test_unusual_priority_warns(self):
        v = validate_config({"workspace": "x", "releases": ["v1"], "priority": "Urgent"})
        assert v.ok
        assert any("priority" in w for w in v.warnings)

    def test_releases_non_string_fails(self):
        v = validate_config({"workspace": "x", "releases": [1, 2]})
        assert not v.ok

    def test_releases_empty_values_fail(self):
        v = validate_config({"workspace": "x", "releases": ["", "  "]})
        assert not v.ok
        assert any("non-empty" in e for e in v.errors)

    def test_duplicate_releases_warn(self):
        v = validate_config({"workspace": "x", "releases": ["v1", "v1"]})
        assert v.ok
        assert any("duplicate release" in w for w in v.warnings)

    def test_planned_window_invalid_datetime_fails(self):
        v = validate_config(
            {"workspace": "x", "releases": ["v1"], "planned_start": "not-a-date"}
        )
        assert not v.ok
        assert any("planned_start" in e for e in v.errors)

    def test_planned_window_end_before_start_fails(self):
        v = validate_config(
            {
                "workspace": "x",
                "releases": ["v1"],
                "planned_start": "2026-04-20T13:00:00-0500",
                "planned_end": "2026-04-20T10:00:00-0500",
            }
        )
        assert not v.ok
        assert any("planned_end" in e for e in v.errors)

    def test_approvers_wrong_type_fails(self):
        v = validate_config({"workspace": "x", "releases": ["v"], "approvers": "alice"})
        assert not v.ok

    def test_non_dict_config_fails(self):
        v = validate_config([])  # type: ignore[arg-type]
        assert not v.ok

    def test_validation_dict_roundtrip(self):
        v = validate_config({})
        d = v.to_dict()
        assert d["ok"] is False and d["errors"]


class TestBuildTicketPayload:
    def test_defaults_filled(self):
        p = build_ticket_payload({"workspace": "default", "releases": ["v1"]})
        assert p["priority"] == "Medium"
        assert p["change_type"] == "Normal"
        assert p["releases"] == ["v1"]

    def test_summary_autogenerated(self):
        p = build_ticket_payload({"workspace": "default", "releases": ["2026.4.04.20"]})
        assert "2026.4.04.20" in p["summary"]

    def test_summary_explicit_preserved(self):
        p = build_ticket_payload(
            {"workspace": "default", "releases": ["v1"], "summary": "Custom"}
        )
        assert p["summary"] == "Custom"

    def test_releases_are_trimmed_and_deduped(self):
        p = build_ticket_payload(
            {"workspace": "default", "releases": ["  v1 ", "v2", "v1"]}
        )
        assert p["releases"] == ["v1", "v2"]


class TestCreateCommand:
    def test_dry_run_produces_payload_output(self, tmp_path, capsys):
        cfg = _good_config(tmp_path)
        deps = CliDeps(create_ticket=lambda p: {"key": "SHOULD_NOT_CALL"})
        rc = main(["create", "--config", str(cfg), "--dry-run"], deps=deps)
        assert rc == 0
        out = capsys.readouterr().out
        assert "dry-run" in out.lower()

    def test_dry_run_json(self, tmp_path, capsys):
        cfg = _good_config(tmp_path)
        rc = main(["create", "--config", str(cfg), "--dry-run", "--json"])
        assert rc == 0
        out = capsys.readouterr().out
        data = json.loads(out)
        assert data["dry_run"] is True
        assert data["payload"]["workspace"] == "default"

    def test_create_calls_deps(self, tmp_path, capsys):
        cfg = _good_config(tmp_path)
        calls = []
        deps = CliDeps(create_ticket=lambda p: (calls.append(p), {"key": "TCKT-99"})[1])
        rc = main(["create", "--config", str(cfg)], deps=deps)
        assert rc == 0
        assert len(calls) == 1
        out = capsys.readouterr().out
        assert "TCKT-99" in out

    def test_missing_config_path_is_usage(self):
        rc = main(["create"])
        # '--config' not passed -> returns EXIT_USAGE from our handler
        assert rc == 2

    def test_invalid_config_returns_validation_exit(self, tmp_path):
        bad = tmp_path / "bad.yml"
        bad.write_text("{}", encoding="utf-8")
        rc = main(["create", "--config", str(bad)])
        assert rc == 5

    def test_create_network_failure_returns_network_exit(self, tmp_path, capsys):
        cfg = _good_config(tmp_path)
        deps = CliDeps(create_ticket=lambda p: (_ for _ in ()).throw(RuntimeError("api down")))
        rc = main(["create", "--config", str(cfg)], deps=deps)
        assert rc == 4
        err = capsys.readouterr().err
        assert "failed to create ticket" in err.lower()


class TestValidateCommand:
    def test_valid_returns_ok(self, tmp_path, capsys):
        cfg = _good_config(tmp_path)
        rc = main(["validate-config", str(cfg)])
        assert rc == 0
        assert "OK" in capsys.readouterr().out

    def test_invalid_returns_validation(self, tmp_path, capsys):
        bad = tmp_path / "b.yml"
        bad.write_text("releases: []\nworkspace: ''\n", encoding="utf-8")
        rc = main(["validate-config", str(bad)])
        assert rc == 5
        assert "FAILED" in capsys.readouterr().out

    def test_json_output(self, tmp_path, capsys):
        cfg = _good_config(tmp_path)
        rc = main(["validate-config", str(cfg), "--json"])
        assert rc == 0
        data = json.loads(capsys.readouterr().out)
        assert data["ok"] is True

    def test_missing_file_returns_config_exit(self, tmp_path):
        rc = main(["validate-config", str(tmp_path / "nope.yml")])
        assert rc == 3


class TestListRecentCommand:
    def test_respects_limit(self, capsys):
        records = [{"key": f"T-{i}", "created": "2026-04-20", "summary": "x"} for i in range(5)]
        deps = CliDeps(list_recent=lambda limit: records[:limit])
        rc = main(["list-recent", "--limit", "3"], deps=deps)
        assert rc == 0
        out = capsys.readouterr().out
        assert out.count("T-") == 3

    def test_limit_zero_is_validation(self, capsys):
        rc = main(["list-recent", "--limit", "0"], deps=CliDeps())
        assert rc == 5

    def test_json_output(self, capsys):
        deps = CliDeps(list_recent=lambda limit: [{"key": "T-1"}])
        rc = main(["list-recent", "--json"], deps=deps)
        assert rc == 0
        data = json.loads(capsys.readouterr().out)
        assert data[0]["key"] == "T-1"

    def test_list_recent_failure_returns_network_exit(self, capsys):
        deps = CliDeps(list_recent=lambda limit: (_ for _ in ()).throw(RuntimeError("jira offline")))
        rc = main(["list-recent"], deps=deps)
        assert rc == 4
        err = capsys.readouterr().err
        assert "failed to list recent tickets" in err.lower()


class TestParser:
    def test_build_parser_requires_command(self, capsys):
        parser = build_parser()
        with pytest.raises(SystemExit):
            parser.parse_args([])

    def test_unknown_command_rejected(self, capsys):
        parser = build_parser()
        with pytest.raises(SystemExit):
            parser.parse_args(["nonexistent"])
